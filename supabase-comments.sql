-- Indiscretos: tabla de comentarios
-- Ejecutar en Supabase > SQL Editor. Compatible con posts.id bigint y usuarios anónimos de Supabase.

create table if not exists public.post_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null,
  content text not null check (char_length(trim(content)) between 1 and 500),
  created_at timestamptz not null default now()
);

create index if not exists post_comments_post_id_created_at_idx
  on public.post_comments (post_id, created_at);

alter table public.post_comments enable row level security;

drop policy if exists "Indiscretos: leer comentarios" on public.post_comments;
create policy "Indiscretos: leer comentarios"
  on public.post_comments
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Indiscretos: comentar como usuario anónimo" on public.post_comments;
create policy "Indiscretos: comentar como usuario anónimo"
  on public.post_comments
  for insert
  to authenticated
  with check (auth.uid() = user_id);

-- No se permite modificar ni borrar comentarios desde el cliente.
